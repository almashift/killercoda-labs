#!/usr/bin/env bash
# Generates every Killercoda scenario from the labs repo, so tasks are written only once.
#   bash .scaffold/generate.sh [path to the istio-fundamentals labs repo]   (default: ../istio-fundamentals)
# Inputs: each lab's meta.env and task.md (labs repo), and here labs.tsv (difficulty, next
# lesson, card description), recaps/<n>.md (the finish page's "What you did") and
# almashift-wait (the progress display). Re-run after changing any of them, then commit.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$HERE")"
LABS="${1:-$REPO_ROOT/../istio-fundamentals}/labs"
OUT="$REPO_ROOT/istio-fundamentals"
COURSE_URL="https://learn.almashift.com/lms/courses/istio-fundamentals"
[ -d "$LABS" ] || { echo "labs repo not found at $LABS" >&2; exit 1; }

items=()
while IFS=$'\t' read -r n difficulty next_lesson next_title description; do
  [[ "$n" =~ ^[0-9]+$ ]] || continue
  src=( "$LABS"/"$(printf '%02d' "$n")"-* ); src="${src[0]}"; dir_name="$(basename "$src")"
  TITLE=""; MINUTES=""
  # shellcheck disable=SC1091
  source "$src/meta.env"
  slug="lab-$n-${dir_name#*-}"; dest="$OUT/$slug"
  rm -rf "$dest"; mkdir -p "$dest/step1" "$dest/assets"
  items+=( "$slug" )

  cat > "$dest/index.json" <<EOF
{
  "title": "Lab $n - $TITLE",
  "description": "$description",
  "difficulty": "$difficulty",
  "time": "$((MINUTES + 5)) minutes",
  "details": {
    "intro": {
      "text": "intro.md",
      "background": "setup.sh",
      "foreground": "foreground.sh"
    },
    "steps": [
      {
        "title": "$TITLE",
        "text": "step1/text.md",
        "verify": "step1/verify.sh"
      }
    ],
    "finish": {
      "text": "finish.md"
    },
    "assets": {
      "host01": [
        { "file": "almashift-wait", "target": "/usr/local/bin", "chmod": "+x" }
      ]
    }
  },
  "backend": {
    "imageid": "kubernetes-kubeadm-1node-4GB"
  }
}
EOF

  cat > "$dest/intro.md" <<EOF
Part of **Istio Fundamentals**, the free course by [AlmaShift](https://almashift.com).
Watch the lessons at [learn.almashift.com](https://learn.almashift.com).

**In this lab:** $description

You get a real Kubernetes cluster for this session. While you read this, the terminal
on the right is installing **Istio 1.27** and the **MeshMart** example store
(about a minute).

MeshMart is a small online shop made of several services: \`web\`, \`catalog\` (v1 and v2),
\`cart\` and \`orders\`. A \`loadgen\` pod sends it a steady stream of shopper traffic.

Click **START** when the terminal says *Your lab is ready*.
EOF

  cat > "$dest/setup.sh" <<'EOF'
#!/bin/bash
# Background script: runs as root when the scenario starts, while the student reads the intro.
# Everything comes from the public labs repo, so the lab itself is maintained in one place.
# Progress goes to $LOG; almashift-wait (an asset) shows its ">>" lines and waits for $READY or $FAILED.
# Generated by .scaffold/generate.sh: edit there, not here.
LOG=/tmp/almashift-setup.log
READY=/tmp/almashift-ready
FAILED=/tmp/almashift-failed
REPO=https://github.com/almashift/istio-fundamentals
REF=master
EOF
  cat >> "$dest/setup.sh" <<EOF
LAB=$n
EOF
  cat >> "$dest/setup.sh" <<'EOF'

exec >>"$LOG" 2>&1
trap 'echo ">> Setup failed (line $LINENO)"; touch "$FAILED"' ERR
set -Eeuo pipefail

echo ">> Downloading the AlmaShift labs"
git clone --quiet --depth 1 --branch "$REF" "$REPO" /root/istio-fundamentals
cd /root/istio-fundamentals

INSTALL_KIND=0 bash setup/install-tools.sh   # Killercoda provides the cluster; no kind needed
bash setup/ensure-cluster.sh                 # without kind: waits for the node, installs Istio

# One scenario = one lab: `lab` hides and refuses the others in this session.
mkdir -p .lab-state
basename labs/"$(printf '%02d' "$LAB")"-* > .lab-state/session-lab

echo ">> Starting lab $LAB (deploying MeshMart)"
lab start "$LAB"
touch "$READY"
EOF

  echo 'almashift-wait; cd /root/istio-fundamentals' > "$dest/foreground.sh"
  cp "$HERE/almashift-wait" "$dest/assets/almashift-wait"

  cat > "$dest/step1/verify.sh" <<EOF
#!/bin/bash
# The CHECK button. Killercoda gives verify scripts only a few seconds, and graders can watch
# traffic for ~15s, so students grade with \`lab check\` in the terminal (which records a pass)
# and CHECK only confirms that record. \`lab start\` clears it.
[ -f /root/istio-fundamentals/.lab-state/$dir_name.passed ]
EOF

  # The task page: task.md without its title lines, each useful command clickable, and
  # Killercoda's own "check your work" ending instead of the terminal one.
  {
    awk '
      NR <= 3 && (/^# / || /^\*\*Domain:\*\*/ || /^$/) { next }
      /^## When you.re done/ { exit }
      /^## Useful commands/  { useful = 1; print; next }
      /^## /                 { useful = 0 }
      useful && /^```/       { block = !block; next }
      useful && block        { if ($0 != "") { print "```"; print $0; print "```{{exec}}"; print "" }; next }
      { print }
    ' "$src/task.md" | cat -s | sed '/./,$!d'
    cat <<'EOF'
## Check your work

Run the grader to see each check:

```
lab check
```{{exec}}

When every check passes, click **CHECK** below to complete the lab
(it confirms that `lab check` has passed).

Stuck? `lab hint`{{exec}} reveals one hint at a time.
EOF
  } > "$dest/step1/text.md"

  {
    echo "# ![AlmaShift](https://www.almashift.com/favicon.ico) Lab $n complete! 🎉"
    echo
    cat "$HERE/recaps/$n.md"
    cat <<EOF

Want the reasoning behind each step? Run \`lab solution\`{{exec}}.

---

### What's next

1. **[Continue with the next lesson: $next_title]($COURSE_URL/learn/$next_lesson)**
2. Browse the [full Istio Fundamentals course]($COURSE_URL) on AlmaShift
EOF
  } > "$dest/finish.md"
  echo "generated $slug"
done < "$HERE/labs.tsv"

{
  echo '{'
  echo '  "items": ['
  for i in "${!items[@]}"; do
    sep=","; [ "$i" -eq $(( ${#items[@]} - 1 )) ] && sep=""
    echo "    { \"path\": \"${items[$i]}\" }$sep"
  done
  echo '  ]'
  echo '}'
} > "$OUT/structure.json"
echo "wrote structure.json (${#items[@]} labs)"
